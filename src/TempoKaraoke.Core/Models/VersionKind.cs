namespace TempoKaraoke.Models;

/// <summary>
/// Тип версии одной и той же песни. Разные <see cref="VersionKind"/> — это разные
/// записи, они не схлопываются: гостю нужен и оригинал, и кавер, и перевод.
/// </summary>
public enum VersionKind
{
    /// <summary>Обычная караоке-минусовка. Тег в имени не пишется.</summary>
    Original = 0,

    /// <summary>Кавер-минус (Karaoke4U): другая аранжировка, часто живые инструменты.</summary>
    Cover = 1,

    /// <summary>«Экстремальное караоке»: заведомо высокий или неудобный вариант.</summary>
    Extreme = 2,

    /// <summary>Эквиритмический перевод: русский текст на месте оригинала.</summary>
    Russian = 3,

    /// <summary>Транскрипция: оригинальный текст, записанный русскими буквами.</summary>
    Transcription = 4,

    /// <summary>Караоке-ремикс.</summary>
    Remix = 5,

    /// <summary>Запись с живого эфира или стрима.</summary>
    Live = 6,

    /// <summary>
    /// Минус с бэк-вокалом (подпевкой). Отдельная версия, а не часть названия:
    /// гостю нужен чистый минус, а этот вариант — для подпевания.
    /// </summary>
    BackingVocal = 7,
}
